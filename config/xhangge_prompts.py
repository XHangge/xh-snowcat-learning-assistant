def build_skill_system_prompt(skill_key, username):
    """拼装某个学习技能的完整系统提示词。

    和 build_system_prompt 的区别：
    - 那个是「聊天用」：人设 + 学习模式
    - 这个是「干技能用」：人设 + 技能任务书
    （学习模式被技能提示词替换掉了，因为此时不该再按聊天模式回答）

    参数：
        skill_key —— "doc" / "qa_shallow" / "qa_medium" / "qa_deep"
        username  —— 用户昵称，允许传空字符串
    返回：
        完整的系统提示词字符串；传了不认识的技能就返回 None，
        调用方据此走普通聊天（不认识的技能名 = 不触发）
    """
    skill_prompt = SKILL_PROMPTS.get(skill_key)
    if skill_prompt is None:
        return None
    real_name = (username or "").strip() or xhangge_config.DEFAULT_USERNAME
    persona = SNOWCAT_PERSONA.replace("{username}", real_name)
    return persona + "\n" + skill_prompt


def build_system_prompt(mode_key, username):
    """拼装最终的系统提示词。

    这段在干什么：
    1. 把人设里的 {username} 占位符替换成真实用户名
       （用户没设置名字时，用默认值"杂狗"）
    2. 根据当前学习模式（mode_key），取出对应模式的提示词
    3. 人设 + 模式提示词拼在一起，就是最终发给模型的 system prompt

    参数：
        mode_key —— "simple" / "detailed" / "teach" 三选一
        username —— 用户设置的昵称，允许传空字符串
    返回：
        一个字符串，完整的系统提示词
    """
    # 用户名为空时使用默认值"杂狗"
    real_name = (username or "").strip() or xhangge_config.DEFAULT_USERNAME
    # 替换人设中的占位符
    persona = SNOWCAT_PERSONA.replace("{username}", real_name)
    # 取出当前模式的提示词；万一传了不认识的值，就退回"简单说喵"
    mode_prompt = MODE_PROMPTS.get(mode_key, MODE_SIMPLE)
    # 人设在前、模式在后，拼接成最终提示词
    return persona + "\n" + mode_prompt


