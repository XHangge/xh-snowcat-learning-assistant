def build_rerank_prompt(query, chunks):
    """把问题和候选片段拼成"重排提示词"。

    参数 chunks：XhanggeRetrievedChunk 列表（已按融合分数排序的候选池）
    返回：拼好的提示词。重排器要求一次给所有片段打分，只做一次模型调用。
    """
    parts = []
    for i, chunk in enumerate(chunks, start=1):
        parts.append(f"[{i}] {chunk.text}")
    return RERANK_PROMPT_TEMPLATE.replace("{query}", query).replace(
        "{chunks}", "\n".join(parts)
    )
