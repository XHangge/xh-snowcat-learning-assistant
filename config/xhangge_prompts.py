def build_agent_system_prompt(username, agent_notes="", max_steps=None):
    """拼装 Agent 模式的完整系统提示词。

    参数：
        username   —— 用户昵称
        agent_notes —— 自进化笔记的内容（Agent 之前任务攒下的经验，
                       从 ~/.xh_snowcat/xhangge_agent_notes.md 读来）
        max_steps  —— 一次任务最多允许的步数（配置里有默认值）
    返回：完整的系统提示词字符串
    """
    from config import xhangge_settings as _cfg

    real_name = (username or "").strip() or xhangge_config.DEFAULT_USERNAME
    persona = SNOWCAT_PERSONA.replace("{username}", real_name)
    steps = max_steps if max_steps is not None else _cfg.XHANGGE_AGENT_MAX_STEPS
    task_book = AGENT_MODE_PROMPT.replace("{max_steps}", str(steps))

    result = persona + "\n" + task_book
    # 有笔记才加这一节（第一次用 Agent 时还没有笔记）
    if agent_notes and agent_notes.strip():
        result += (
            "\n【你从之前的任务里攒下的经验笔记】\n"
            + agent_notes.strip()
            + "\n（合理利用这些经验，但情况变了就别硬套喵）"
        )
    return result


# ============================================================
# RAG：检索结果拼进上下文的包装模板（模块五）
# ============================================================
# 聊天前，服务层会拿着用户的问题去知识库里找出最相关的几段文字。
# 但不能把"裸文字"直接塞给模型——它不知道这几段是哪来的、
# 该怎么对待。所以要用下面这个模板包一层，明确告诉它：
# 这是参考资料，答案优先从这里找。

RAG_CONTEXT_TEMPLATE = """

【📚 知识库参考资料（回答时请优先依据这些内容）】
下面是从用户的知识库里检索到的、和他的问题最相关的片段。
回答规则：
1. 答案优先从这些片段里找，找到了就用自己的话讲清楚
2. 片段里有出处文件名的，回答末尾用一行小字标注参考了哪些文件，
   格式：📎 参考：《文件名》
3. 片段里没有相关内容时，就按你自己的知识正常回答，
   但不要谎称内容来自知识库
4. 片段内容和你的知识冲突时，以片段为准（那是用户的私有资料）

{chunks}
"""


def build_rag_context_section(retrieved_chunks):
    """把检索到的片段列表拼成一段可以直接接在系统提示词后面的文字。

    参数 retrieved_chunks：XhanggeRetrievedChunk 列表
    （来自 services/xhangge_kb_service.py 的 xhangge_retrieve()）
    返回：拼好的整段文字；一个片段都没有时返回空字符串
    （调用方拿到空字符串就当没用知识库，不加这一节）。
    """
    if not retrieved_chunks:
        return ""
    parts = []
    for i, chunk in enumerate(retrieved_chunks, start=1):
        parts.append(
            f"【片段 {i}】来自《{chunk.file_name}》（{chunk.kb_name}）：\n{chunk.text}"
        )
    return RAG_CONTEXT_TEMPLATE.replace("{chunks}", "\n\n".join(parts))


